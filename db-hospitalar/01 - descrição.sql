DESCRIÇÃO DO PROJETO:
---------------------------------------------------------

Este projeto consiste na criação e análise de um banco de dados fictício de uma clínica hospitalar, 
com o objetivo de demonstrar habilidades em modelagem de dados, SQL Básico ao Intermediario e análise de negócios.

O QUE FOI DESENVOLVIDO:
---------------------------------------------------------

- Criação do banco de dados db_hospitalar
- Modelagem de 5 tabelas com referencias
- Inserção de dados 
- 10 consultas de negócio 

OBJETIVO PRINCIPAL:
---------------------------------------------------------

Demonstrar conhecimento prático em MySQL, incluindo:
• Criação de tabelas e relacionamentos (PK e FK)
• Manipulação e inserção de dados
• Consultas SQL com JOINs, GROUP BY, ORDER BY e CASE
• Funções de agregação (SUM, COUNT, AVG)
• Análise orientada a negócios (faturamento, desempenho e indicadores)

Tecnologias utilizadas: MySQL Workbench 8.0

EXPLICAÇÕES DAS GUIAS:
---------------------------------------------------------
1º Guia - Descrição do Projeto (este arquivo)
2º Guia - Criação das Tabelas + Inserção de Dados
3º Guia - 10 Perguntas de Negócio + Respostas em SQL

Perguntas de negócio:
	1. Qual foi o faturamento total do hospital no período?
	2. Quais são os 5 médicos que mais geraram faturamento?
	3. Quais especialidades geram mais faturamento e mais consultas?
	4. Qual a taxa de cancelamento e não comparecimento de consultas?
	5. Quais são os 5 pacientes que mais frequentam o hospital?
	6. Qual é o ticket médio por consulta e por especialidade?
    7. Qual forma de pagamento é mais utilizada e qual gera mais receita?
	8. Qual foi a evolução de faturamento mês a mês?
	9. Quais médicos possuem mais pacientes únicos atendidos?
	10. Quais consultas estão com pagamento pendente ou em atraso?

DESAFIOS ENCONTRADOS:
---------------------------------------------------------
