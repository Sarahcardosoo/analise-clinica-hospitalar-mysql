fortalecer as consultas SQL para responder não apenas ao problema principal, mas também as outras possíveis dúvidas que poderiam surgir durante a análise. Além disso, 
aprendi a entender o banco de dados e os dados inseridos, e a me colocar no lugar das pessoas que buscam a informação, para obter um entendimento melhor sobre a pergunta de negocio

